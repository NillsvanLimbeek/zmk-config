#!/usr/bin/env python3
"""Generate a 140x68 1-bit LVGL image (art.c) for the nice!view peripheral screen.

Usage: python3 tools/gen_art.py   (rewrites boards/shields/nice_view_custom/widgets/art.c)
Edit SPRITE / STARS below to change the picture.
"""
import random
from pathlib import Path

W, H = 140, 68
NAME = "invader"
OUT = Path(__file__).resolve().parent.parent / "boards/shields/nice_view_custom/widgets/art.c"

# 11x8 space invader
SPRITE = [
    "..#.....#..",
    "...#...#...",
    "..#######..",
    ".##.###.##.",
    "###########",
    "#.#######.#",
    "#.#.....#.#",
    "...##.##...",
]
SCALE = 6

px = [[0] * W for _ in range(H)]  # 1 = lit pixel

# stars (deterministic)
rnd = random.Random(58)
for _ in range(45):
    px[rnd.randrange(H)][rnd.randrange(W)] = 1

# sprite, centred, with a cleared margin so stars don't touch it
sw, sh = len(SPRITE[0]) * SCALE, len(SPRITE) * SCALE
ox, oy = (W - sw) // 2, (H - sh) // 2
for y in range(oy - 3, oy + sh + 3):
    for x in range(ox - 3, ox + sw + 3):
        if 0 <= x < W and 0 <= y < H:
            px[y][x] = 0
for sy, row in enumerate(SPRITE):
    for sx, c in enumerate(row):
        if c == "#":
            for dy in range(SCALE):
                for dx in range(SCALE):
                    px[oy + sy * SCALE + dy][ox + sx * SCALE + dx] = 1

stride = (W + 7) // 8
data = bytearray()
for row in px:
    for bx in range(stride):
        b = 0
        for bit in range(8):
            x = bx * 8 + bit
            if x < W and row[x]:
                b |= 0x80 >> bit
        data.append(b)

def fmt(bs):
    return "\n".join("        " + ", ".join(f"0x{v:02x}" for v in bs[i:i + 15]) + ","
                     for i in range(0, len(bs), 15))

OUT.write_text(f"""/* Generated by tools/gen_art.py - do not edit by hand. */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {NAME}_map[] = {{
#if CONFIG_NICE_VIEW_WIDGET_INVERTED
        0xff, 0xff, 0xff, 0xff, /*Color of index 0*/
        0x00, 0x00, 0x00, 0xff, /*Color of index 1*/
#else
        0x00, 0x00, 0x00, 0xff, /*Color of index 0*/
        0xff, 0xff, 0xff, 0xff, /*Color of index 1*/
#endif

{fmt(data)}
}};

const lv_img_dsc_t {NAME} = {{
    .header.cf = LV_COLOR_FORMAT_I1,

    .header.w = {W},
    .header.h = {H},
    .data_size = {len(data) + 8},
    .data = {NAME}_map,
}};
""")
print(f"wrote {OUT} ({len(data)} bytes of pixels)")
for row in px[::2]:
    print("".join("#" if row[x] else " " for x in range(0, W, 1)))
